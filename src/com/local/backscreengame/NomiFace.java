package com.local.backscreengame;

/**
 * NOMI 表情精灵 v4 —— 实心脸 + 挖空五官。
 *
 * v3 是空心轮廓线，点亮率只有 17.4%，在 MiniLED 上就是一圈细线，
 * 而且 26% 的屏是连续空白行 —— 看起来「显示很少」。
 * v4 把脸填实、五官挖空（剪影娃娃），点亮率约 36%。
 *
 * 关键修正：
 *   - 眼睛是 2x2 小方洞，不是 3x3（大洞像靶心/黑洞）。
 *   - talk 的嘴从小 H 形改成小菱形 —— H 形像机械格栅、钥匙孔。
 *   - think 的右眼补成 2x2（原来只有 1 行，读作坏点）。
 *   - 脸下移让位：底部要放实时声音柱，所以 FACE_SHIFT=1。
 */
public final class NomiFace {

    private NomiFace() { }

    private static final String[] ORDER = {
        "idle",
        "happy",
        "think",
        "talk",
        "sleep",
        "blink",
    };

    /** 6 帧表情循环。fps=2 让眨眼自然。 */
    public static SpriteAnim anim() {
        String[] f = {
            // idle —
            ".................\n.................\n.................\n.......###.......\n.......###.......\n.....#######.....\n....#########....\n...###########...\n.###############.\n.####..###..####.\n.####..###..####.\n.###############.\n..#############..\n..#############..\n....#########....\n.....##...##.....\n......#####......\n......#####......\n......#####......\n.......###.......\n.................\n.................\n.................",

            // happy —
            ".................\n.................\n.................\n.......###.......\n.......###.......\n.....#######.....\n....#########....\n...###########...\n.###############.\n.#####.####.####.\n.####.#.##.#.###.\n.###############.\n..#############..\n..#############..\n....#.#####.#....\n.....#.###.#.....\n......#...#......\n......#####......\n......#####......\n.......###.......\n.................\n.................\n.................",

            // think —
            ".................\n.................\n.................\n.......###.......\n.......###......#\n.....#######.....\n....#########..#.\n...###########...\n.#########..####.\n.####..###..####.\n.####..#########.\n.###############.\n..#############..\n..#############..\n....#########....\n.....##..###.....\n......##..#......\n......#####......\n......#####......\n.......###.......\n.................\n.................\n.................",

            // talk —
            ".................\n.................\n.................\n.......###.......\n.......###.......\n.....#######.....\n....#########....\n...###########...\n.###############.\n.####..###..####.\n.####..###..####.\n.###############.\n..#############..\n..#############..\n....#########....\n.....##.#..#.....\n......##..#......\n......#####......\n......#####......\n.......###.......\n.................\n.................\n.................",

            // sleep —
            ".................\n............###..\n..............#..\n.......###...#...\n.......###..###..\n.....#######.....\n....#########....\n...###########...\n.###############.\n.###############.\n.###############.\n.###############.\n..#############..\n..###..###..###..\n....#########....\n.....#######.....\n......#...#......\n......#####......\n......#####......\n.......###.......\n.................\n.................\n.................",

            // blink —
            ".................\n.................\n.................\n.......###.......\n.......###.......\n.....#######.....\n....#########....\n...###########...\n.###############.\n.####..#########.\n.####..###...###.\n.###############.\n..#############..\n..#############..\n....#########....\n.....##...##.....\n......#####......\n......#####......\n......#####......\n.......###.......\n.................\n.................\n.................",

        };
        return new SpriteAnim(f, 2);
    }

    /** 按名字取单帧（预览/测试用）。返回整帧字符串，行用 \n 分隔。 */
    public static String frame(String name) {
        String[] fr = anim().frames;
        for (int i = 0; i < ORDER.length; i++) {
            if (ORDER[i].equals(name)) {
                return fr[i];
            }
        }
        return fr[0];
    }
}
